    "### 为什么 ReLU 是当前主流选择？",
    "",
    "1. **计算高效**：只需一次比较操作",
    "2. **缓解梯度消失**：正半轴梯度恒为 1",
    "3. **稀疏激活**：约一半神经元处于激活状态，更接近生物神经元",
