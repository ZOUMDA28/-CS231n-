    "",
    "### 直觉",
    "",
    "Adam (Adaptive Moment Estimation) 结合了：",
    "- **动量思想**（一阶矩估计）：积累历史梯度方向",
    "- **RMSProp 思想**（二阶矩估计）：为每个参数自适应调整学习率",
