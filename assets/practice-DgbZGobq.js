    "# Implement transposed convolution (simple 1D then 2D)\\n",
    "def transposed_conv2d(input, weight, stride=1, padding=0):\\n",
    "    '''Simple transposed convolution implementation.\\n",
    "    \\n",
    "    Args:\\n",
    "        input: (batch, in_channels, H, W)\\n",
    "        weight: (in_channels, out_channels, kH, kW)\\n",
    "        stride: int or tuple\\n",
    "        padding: int or tuple\\n",
    "    \\n",
    "    Returns:\\n",
    "        output: (batch, out_channels, H_out, W_out)\\n",
    "    '''\\n",
    "    batch, in_c, H_in, W_in = input.shape\\n",
    "    in_c_w, out_c, kH, kW = weight.shape\\n",
    "    \\n",
    "    assert in_c == in_c_w, 'Input channels mismatch'\\n",
    "    \\n",
    "    # Output size\\n",
    "    H_out = (H_in - 1) * stride - 2 * padding + kH\\n",
    "    W_out = (W_in - 1) * stride - 2 * padding + kW\\n",
    "    \\n",
    "    output = np.zeros((batch, out_c, H_out, W_out))\\n",
    "    \\n",
    "    # Scatter input values into output according to kernel weights\\n",
    "    for b in range(batch):\\n",
    "        for ic in range(in_c):\\n",
    "            for oc in range(out_c):\\n",
    "                for i in range(H_in):\\n",
    "                    for j in range(W_in):\\n",
    "                        val = input[b, ic, i, j]\\n",
    "                        # Position in output\\n",
    "                        h_start = i * stride - padding\\n",
    "                        w_start = j * stride - padding\\n",
    "                        # Overlap with kernel\\n",
    "                        for kh in range(kH):\\n",
    "                            for kw in range(kW):\\n",
    "                                h_out = h_start + kh\\n",
    "                                w_out = w_start + kw\\n",
    "                                if 0 <= h_out < H_out and 0 <= w_out < W_out:\\n",
    "                                    output[b, oc, h_out, w_out] += val * weight[ic, oc, kh, kw]\\n",
    "    \\n",
    "    return output\\n",
    "\\n",
    "# Test: 2x2 input with 3x3 kernel, stride=1, padding=0\\n",
