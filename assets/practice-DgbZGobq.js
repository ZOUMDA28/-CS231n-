    "## 2. FCN：全卷积网络\\n",
    "\\n",
    "### 为什么不用全连接层？\\n",
    "\\n",
    "传统的 CNN（如 VGG）最后接全连接层输出类别概率。但全连接层：\\n",
    "1. 固定了输入尺寸\\n",
    "2. 丢失了空间信息\\n",
    "3. 不能输出空间映射\\n",
    "\\n",
    "### FCN 的创新\\n",
    "\\n",
    "[[Long et al., 2015]](https://arxiv.org/abs/1411.4038)\\n",
    "\\n",
    "**核心思想**：把全连接层换成卷积层，网络可以接受任意尺寸的输入，输出空间热图。\\n",
    "\\n",
    "\`\`\`\\n",
    "传统 CNN: 图像 → 卷积 → 池化 → ... → 全连接 → 类别概率（标量）\\n",
    "FCN:      图像 → 卷积 → 池化 → ... → 1x1 卷积 → 分割热图（空间图）\\n",
    "\`\`\`\\n",
    "\\n",
    "### 上采样问题\\n",
