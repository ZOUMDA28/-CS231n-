    "\\n",
    "### IoU（交并比 / Jaccard Index）\\n",
    "\\n",
    "IoU = 交集面积 / 并集面积 = |A ∩ B| / |A ∪ B|\\n",
    "\\n",
    "范围：[0, 1]，越大越好。\\n",
    "\\n",
    "### Dice 系数\\n",
    "\\n",
    "Dice = 2 * |A ∩ B| / (|A| + |B|)\\n",
    "\\n",
    "和 IoU 正相关，但对小目标更敏感。\\n",
    "\\n",
    "### Dice Loss\\n",
    "\\n",
    "Dice Loss = 1 - Dice\\n",
    "\\n",
    "直接优化 Dice 系数，特别适合类别不平衡的情况（如医学影像中目标很小）。\\n",
