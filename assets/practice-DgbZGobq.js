    "# Implement simple U-Net style network\\n",
    "class SimpleUNet:\\n",
    "    '''Simple U-Net style network for 2D toy segmentation.\\n",
    "    \\n",
    "    Uses numpy arrays for weights, simulating the architecture.\\n",
    "    '''\\n",
    "    def __init__(self, in_channels=1, out_channels=2, base_filters=8):\\n",
    "        # Encoder (downsampling path)\\n",
    "        # Level 1: conv\\n",
    "        self.enc1_W1 = np.random.randn(in_channels, base_filters, 3, 3) * 0.1\\n",
    "        self.enc1_b1 = np.zeros(base_filters)\\n",
    "        self.enc1_W2 = np.random.randn(base_filters, base_filters, 3, 3) * 0.1\\n",
    "        self.enc1_b2 = np.zeros(base_filters)\\n",
    "        \\n",
    "        # Level 2: pool + conv\\n",
    "        self.enc2_W1 = np.random.randn(base_filters, base_filters*2, 3, 3) * 0.1\\n",
    "        self.enc2_b1 = np.zeros(base_filters*2)\\n",
    "        self.enc2_W2 = np.random.randn(base_filters*2, base_filters*2, 3, 3) * 0.1\\n",
    "        self.enc2_b2 = np.zeros(base_filters*2)\\n",
    "        \\n",
    "        # Bottleneck\\n",
    "        self.bottl_W1 = np.random.randn(base_filters*2, base_filters*4, 3, 3) * 0.1\\n",
    "        self.bottl_b1 = np.zeros(base_filters*4)\\n",
    "        self.bottl_W2 = np.random.randn(base_filters*4, base_filters*2, 3, 3) * 0.1\\n",
    "        self.bottl_b2 = np.zeros(base_filters*2)\\n",
    "        \\n",
    "        # Decoder (upsampling path)\\n",
    "        # Level 2 up: transposed conv + concat + conv\\n",
    "        self.up2_W = np.random.randn(base_filters*2, base_filters*2, 2, 2) * 0.1  # transposed conv weight\\n",
    "        self.dec2_W1 = np.random.randn(base_filters*4, base_filters*2, 3, 3) * 0.1  # after concat\\n",
    "        self.dec2_b1 = np.zeros(base_filters*2)\\n",
    "        self.dec2_W2 = np.random.randn(base_filters*2, base_filters, 3, 3) * 0.1\\n",
    "        self.dec2_b2 = np.zeros(base_filters)\\n",
    "        \\n",
    "        # Level 1 up\\n",
    "        self.up1_W = np.random.randn(base_filters, base_filters, 2, 2) * 0.1\\n",
    "        self.dec1_W1 = np.random.randn(base_filters*2, base_filters, 3, 3) * 0.1\\n",
    "        self.dec1_b1 = np.zeros(base_filters)\\n",
    "        self.dec1_W2 = np.random.randn(base_filters, out_channels, 1, 1) * 0.1  # final 1x1 conv\\n",
    "        self.dec1_b2 = np.zeros(out_channels)\\n",
    "    \\n",
    "    def _conv2d(self, x, W, b):\\n",
    "        '''Simple conv2d with padding=1 to keep size.'''\\n",
    "        batch, in_c, H, W_in = x.shape\\n",
    "        in_c_w, out_c, kH, kW = W.shape\\n",
    "        pad = kH // 2\\n",
    "        H_out = H\\n",
    "        W_out = W_in\\n",
    "        \\n",
    "        out = np.zeros((batch, out_c, H_out, W_out))\\n",
    "        for b_idx in range(batch):\\n",
    "            for oc in range(out_c):\\n",
    "                for ic in range(in_c):\\n",
    "                    for i in range(H_out):\\n",
    "                        for j in range(W_out):\\n",
    "                            for kh in range(kH):\\n",
    "                                for kw in range(kW):\\n",
    "                                    h_in = i + kh - pad\\n",
    "                                    w_in = j + kw - pad\\n",
    "                                    if 0 <= h_in < H and 0 <= w_in < W_in:\\n",
    "                                        out[b_idx, oc, i, j] += x[b_idx, ic, h_in, w_in] * W[ic, oc, kh, kw]\\n",
    "                out[b_idx, oc] += b[oc]\\n",
    "        \\n",
    "        return np.maximum(out, 0)  # ReLU\\n",
    "    \\n",
    "    def _maxpool2d(self, x, size=2):\\n",
    "        '''Simple 2x2 max pooling.'''\\n",
    "        batch, C, H, W = x.shape\\n",
    "        H_out = H // size\\n",
    "        W_out = W // size\\n",
    "        out = np.zeros((batch, C, H_out, W_out))\\n",
    "        for b in range(batch):\\n",
    "            for c in range(C):\\n",
    "                for i in range(H_out):\\n",
    "                    for j in range(W_out):\\n",
    "                        patch = x[b, c, i*size:(i+1)*size, j*size:(j+1)*size]\\n",
    "                        out[b, c, i, j] = np.max(patch)\\n",
    "        return out\\n",
    "    \\n",
    "    def _upsample(self, x, W):\\n",
    "        '''Transposed conv upsampling with stride=2.'''\\n",
    "        return transposed_conv2d(x, W, stride=2, padding=0)\\n",
    "    \\n",
    "    def forward(self, x):\\n",
