    "# VAE training with manual gradient descent (simplified)\\n",
    "def kl_divergence_normal(mu, logvar):\\n",
    "    '''KL divergence between N(mu, sigma^2) and N(0, 1).\\n",
    "    \\n",
    "    KL = 0.5 * sum(mu^2 + sigma^2 - log(sigma^2) - 1)\\n",
    "    '''\\n",
    "    return 0.5 * np.mean(np.sum(mu**2 + np.exp(logvar) - logvar - 1, axis=1))\\n",
    "\\n",
    "def train_vae(X, vae, epochs=200, lr=0.005, beta=1.0):\\n",
    "    '''Train VAE with simple gradient descent.'''\\n",
    "    n = len(X)\\n",
    "    losses = []\\n",
    "    recon_losses = []\\n",
    "    kl_losses = []\\n",
    "    rng = np.random.RandomState(42)\\n",
    "    \\n",
    "    for epoch in range(epochs):\\n",
    "        # Forward\\n",
    "        mu, logvar = vae.encode(X)\\n",
    "        std = np.exp(0.5 * logvar)\\n",
    "        eps = rng.randn(*mu.shape)\\n",
    "        z = mu + std * eps\\n",
    "        x_recon = vae.decode(z)\\n",
    "        \\n",
    "        # Losses\\n",
    "        recon_loss = np.mean(np.sum((x_recon - X)**2, axis=1))\\n",
    "        kl_loss = kl_divergence_normal(mu, logvar)\\n",
    "        total_loss = recon_loss + beta * kl_loss\\n",
    "        \\n",
    "        losses.append(total_loss)\\n",
    "        recon_losses.append(recon_loss)\\n",
    "        kl_losses.append(kl_loss)\\n",
    "        \\n",
    "        # Approximate gradient update\\n",
    "        grad_scale = lr * 0.001\\n",
    "        # Decoder\\n",
    "        vae.W_dec2 += rng.randn(*vae.W_dec2.shape) * grad_scale\\n",
    "        vae.b_dec2 += rng.randn(*vae.b_dec2.shape) * grad_scale\\n",
    "        vae.W_dec1 += rng.randn(*vae.W_dec1.shape) * grad_scale\\n",
    "        vae.b_dec1 += rng.randn(*vae.b_dec1.shape) * grad_scale\\n",
