    "# Implement simple GAN on 2D ring data\\n",
    "class SimpleGAN:\\n",
    "    '''Simple GAN for 2D data.'''\\n",
    "    def __init__(self, data_dim=2, latent_dim=4, hidden_dim=16):\\n",
    "        self.latent_dim = latent_dim\\n",
    "        # Generator: z -> x\\n",
    "        self.G_W1 = np.random.randn(latent_dim, hidden_dim) * 0.1\\n",
    "        self.G_b1 = np.zeros(hidden_dim)\\n",
    "        self.G_W2 = np.random.randn(hidden_dim, data_dim) * 0.1\\n",
    "        self.G_b2 = np.zeros(data_dim)\\n",
    "        # Discriminator: x -> probability\\n",
    "        self.D_W1 = np.random.randn(data_dim, hidden_dim) * 0.1\\n",
