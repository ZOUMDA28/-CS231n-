    "# VAE implementation (numpy version)\\n",
    "class SimpleVAE:\\n",
    "    '''Simple VAE with 2D data and 1D latent space.'''\\n",
    "    def __init__(self, data_dim=2, latent_dim=1, hidden_dim=16):\\n",
    "        self.latent_dim = latent_dim\\n",
    "        # Encoder weights: x -> mu, logvar\\n",
    "        self.W_enc = np.random.randn(data_dim, hidden_dim) * 0.1\\n",
    "        self.b_enc = np.zeros(hidden_dim)\\n",
    "        self.W_mu = np.random.randn(hidden_dim, latent_dim) * 0.1\\n",
    "        self.b_mu = np.zeros(latent_dim)\\n",
    "        self.W_logvar = np.random.randn(hidden_dim, latent_dim) * 0.1\\n",
    "        self.b_logvar = np.zeros(latent_dim)\\n",
    "        # Decoder weights: z -> x_recon\\n",
    "        self.W_dec1 = np.random.randn(latent_dim, hidden_dim) * 0.1\\n",
    "        self.b_dec1 = np.zeros(hidden_dim)\\n",
    "        self.W_dec2 = np.random.randn(hidden_dim, data_dim) * 0.1\\n",
    "        self.b_dec2 = np.zeros(data_dim)\\n",
    "    \\n",
    "    def encode(self, x):\\n",
    "        '''Encode x to latent distribution parameters.'''\\n",
    "        h = np.tanh(x @ self.W_enc + self.b_enc)\\n",
    "        mu = h @ self.W_mu + self.b_mu\\n",
    "        logvar = h @ self.W_logvar + self.b_logvar\\n",
    "        return mu, logvar\\n",
    "    \\n",
    "    def reparameterize(self, mu, logvar):\\n",
    "        '''Reparameterization trick: z = mu + std * eps.'''\\n",
    "        std = np.exp(0.5 * logvar)\\n",
    "        eps = np.random.randn(*mu.shape)\\n",
    "        return mu + std * eps\\n",
    "    \\n",
    "    def decode(self, z):\\n",
    "        '''Decode z to reconstruction.'''\\n",
    "        h = np.tanh(z @ self.W_dec1 + self.b_dec1)\\n",
    "        return h @ self.W_dec2 + self.b_dec2\\n",
    "    \\n",
    "    def forward(self, x):\\n",
    "        '''Full forward pass.'''\\n",
    "        mu, logvar = self.encode(x)\\n",
    "        z = self.reparameterize(mu, logvar)\\n",
    "        x_recon = self.decode(z)\\n",
    "        return x_recon, mu, logvar\\n",
