    "# Simple domain adaptation: align mean and variance\\n",
    "def align_distributions(X_source, X_target):\\n",
    "    '''Align target distribution to match source mean and variance.'''\\n",
    "    src_mean = np.mean(X_source, axis=0)\\n",
    "    src_std = np.std(X_source, axis=0) + 1e-8\\n",
    "    tgt_mean = np.mean(X_target, axis=0)\\n",
    "    tgt_std = np.std(X_target, axis=0) + 1e-8\\n",
    "    return (X_target - tgt_mean) / tgt_std * src_std + src_mean\\n",
    "\\n",
    "X_tgt_aligned = align_distributions(X_src, X_tgt)\\n",
