    "# Helper functions\\n",
    "def softmax(x):\\n",
    "    '''Compute softmax along last axis.'''\\n",
    "    x = x - np.max(x, axis=-1, keepdims=True)\\n",
    "    exp_x = np.exp(x)\\n",
    "    return exp_x / np.sum(exp_x, axis=-1, keepdims=True)\\n",
    "\\n",
    "def cross_entropy_loss(logits, y):\\n",
    "    '''Compute cross-entropy loss.'''\\n",
    "    probs = softmax(logits)\\n",
    "    n = len(y)\\n",
    "    return -np.mean(np.log(probs[np.arange(n), y] + 1e-10))\\n",
    "\\n",
    "# Feature extraction training\\n",
    "def train_feature_extraction(X_train, y_train, X_test, y_test, model, num_classes=2, epochs=100, lr=0.05):\\n",
    "    '''Feature extraction: freeze backbone, only train new classifier.'''\\n",
    "    n = len(X_train)\\n",
    "    losses, accs = [], []\\n",
    "    train_feat = model.extract_features(X_train)\\n",
    "    test_feat = model.extract_features(X_test)\\n",
    "    dim = train_feat.shape[1]\\n",
    "    fc_w = np.random.randn(num_classes, dim) * 0.05\\n",
    "    fc_b = np.zeros(num_classes)\\n",
    "    \\n",
    "    for epoch in range(epochs):\\n",
    "        logits = train_feat @ fc_w.T + fc_b\\n",
    "        loss = cross_entropy_loss(logits, y_train)\\n",
    "        losses.append(loss)\\n",
    "        preds = np.argmax(logits, axis=1)\\n",
    "        accs.append(np.mean(preds == y_train))\\n",
    "        probs = softmax(logits)\\n",
    "        dlogits = probs\\n",
    "        dlogits[np.arange(n), y_train] -= 1\\n",
    "        dlogits /= n\\n",
    "        fc_w -= lr * (dlogits.T @ train_feat)\\n",
    "        fc_b -= lr * np.sum(dlogits, axis=0)\\n",
    "    \\n",
    "    test_logits = test_feat @ fc_w.T + fc_b\\n",
    "    test_acc = np.mean(np.argmax(test_logits, axis=1) == y_test)\\n",
    "    return (fc_w, fc_b), losses, accs, test_acc\\n",
    "\\n",
