    "## 2. 迁移学习的直觉：特征的可迁移性\\n",
    "\\n",
    "### 不同层学到了什么？\\n",
    "\\n",
    "| 层级 | 学到的特征 | 可迁移性 |\\n",
    "|------|-----------|---------|\\n",
    "| 底层（Conv1-2） | 边缘、纹理、颜色 | 很高（通用） |\\n",
    "| 中层（Conv3-5） | 形状、部件 | 较高 |\\n",
    "| 高层（FC6-7） | 物体类别、场景 | 较低（任务相关） |\\n",
    "| 分类器（FC8） | 具体类别决策 | 不可迁移 |\\n",
    "\\n",
