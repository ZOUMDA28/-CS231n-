    "# Step 1: Create a simulated pretrained small CNN\\n",
    "class SimpleCNN:\\n",
    "    '''Simple CNN for demonstration (NumPy implementation).\\n",
    "    \\n",
    "    Structure:\\n",
    "        Conv1 (3x3, 8 filters) -> ReLU -> MaxPool\\n",
    "        Conv2 (3x3, 16 filters) -> ReLU -> MaxPool\\n",
    "        Global Average Pooling -> FC classifier\\n",
    "    '''\\n",
    "    def __init__(self, in_channels=3, num_classes=10):\\n",
    "        self.conv1_weights = np.random.randn(8, in_channels, 3, 3) * 0.1\\n",
    "        self.conv1_bias = np.zeros(8)\\n",
    "        self.conv2_weights = np.random.randn(16, 8, 3, 3) * 0.1\\n",
    "        self.conv2_bias = np.zeros(16)\\n",
    "        self.fc_weights = np.random.randn(num_classes, 16) * 0.1\\n",
    "        self.fc_bias = np.zeros(num_classes)\\n",
    "        \\n",
    "    def relu(self, x):\\n",
    "        return np.maximum(0, x)\\n",
    "    \\n",
    "    def conv2d(self, x, weights, bias):\\n",
    "        '''Simple 2D convolution (educational implementation).'''\\n",
    "        batch, c_in, h, w = x.shape\\n",
    "        c_out, _, kh, kw = weights.shape\\n",
    "        out_h, out_w = h - kh + 1, w - kw + 1\\n",
    "        out = np.zeros((batch, c_out, out_h, out_w))\\n",
    "        for i in range(kh):\\n",
    "            for j in range(kw):\\n",
    "                x_slice = x[:, :, i:i+out_h, j:j+out_w]\\n",
    "                for oc in range(c_out):\\n",
    "                    out[:, oc] += np.sum(x_slice * weights[oc, :, i, j][:, None, None], axis=1)\\n",
    "        out += bias[None, :, None, None]\\n",
    "        return out\\n",
    "    \\n",
    "    def max_pool(self, x, size=2):\\n",
    "        '''2x2 max pooling.'''\\n",
    "        batch, c, h, w = x.shape\\n",
    "        out_h, out_w = h // size, w // size\\n",
    "        out = np.zeros((batch, c, out_h, out_w))\\n",
    "        for i in range(size):\\n",
    "            for j in range(size):\\n",
    "                out = np.maximum(out, x[:, :, i::size, j::size])\\n",
    "        return out\\n",
    "    \\n",
    "    def global_avg_pool(self, x):\\n",
    "        '''Global average pooling.'''\\n",
    "        return np.mean(x, axis=(2, 3))\\n",
    "    \\n",
    "    def extract_features(self, x):\\n",
    "        '''Extract features before classifier.'''\\n",
    "        h = self.relu(self.conv2d(x, self.conv1_weights, self.conv1_bias))\\n",
    "        h = self.max_pool(h)\\n",
    "        h = self.relu(self.conv2d(h, self.conv2_weights, self.conv2_bias))\\n",
    "        h = self.max_pool(h)\\n",
    "        return self.global_avg_pool(h)\\n",
    "    \\n",
    "    def forward(self, x):\\n",
    "        features = self.extract_features(x)\\n",
    "        return features @ self.fc_weights.T + self.fc_bias\\n",
    "\\n",
    "print('SimpleCNN class defined!')\\n"
