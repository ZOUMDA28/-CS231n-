    "# Implement volume rendering (ray marching)\\n",
    "def volume_render(densities, colors, distances):\\n",
    "    '''Volume rendering along a ray.\\n",
    "    \\n",
    "    Args:\\n",
    "        densities: density values at each sample point (N,)\\n",
    "        colors: color values at each sample point (N,)\\n",
    "        distances: distance between sample points (N,) or scalar\\n",
    "    \\n",
    "    Returns:\\n",
    "        pixel_color: final rendered pixel color\\n",
    "        transmittance: remaining transmittance\\n",
    "    '''\\n",
    "    if np.isscalar(distances):\\n",
    "        deltas = np.full_like(densities, distances)\\n",
    "    else:\\n",
    "        deltas = distances\\n",
    "    \\n",
    "    # Alpha values: 1 - exp(-sigma * delta)\\n",
    "    alphas = 1 - np.exp(-densities * deltas)\\n",
    "    \\n",
    "    # Transmittance: T_i = exp(-sum_{j< i} sigma_j * delta_j)\\n",
    "    # Cumulative sum of densities * deltas\\n",
    "    cum_density = np.cumsum(densities * deltas)\\n",
    "    # Shift: T_1 = 1, T_i depends on sum up to i-1\\n",
    "    transmittance = np.exp(-np.concatenate([[0], cum_density[:-1]]))\\n",
    "    \\n",
    "    # Weight of each sample: T_i * alpha_i\\n",
    "    weights = transmittance * alphas\\n",
    "    \\n",
    "    # Final color\\n",
    "    pixel_color = np.sum(weights * colors)\\n",
    "    \\n",
    "    return pixel_color, transmittance, weights\\n",
    "\\n",
    "# Manual calculation test\\n",
    "densities = np.array([0.5, 2.0, 0.1])\\n",
    "colors = np.array([0.8, 0.3, 0.9])\\n",
    "deltas = 1.0\\n",
