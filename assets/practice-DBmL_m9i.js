    "# Implement simple SimCLR-style training on toy data\\n",
    "def augment_2d(X, strength=0.5, seed=None):\\n",
    "    '''Simple 2D data augmentation (add noise + slight rotation).'''\\n",
    "    rng = np.random.RandomState(seed)\\n",
    "    # Add noise\\n",
    "    noise = rng.randn(*X.shape) * strength\\n",
    "    # Random rotation (small angle)\\n",
    "    angle = rng.uniform(-0.3, 0.3)\\n",
    "    rot_matrix = np.array([[np.cos(angle), -np.sin(angle)],\\n",
    "                           [np.sin(angle), np.cos(angle)]])\\n",
    "    X_aug = X @ rot_matrix.T + noise\\n",
    "    return X_aug\\n",
    "\\n",
    "# Generate toy data: 4 clusters representing 4 classes\\n",
    "def generate_toy_data(n_samples=200, n_classes=4, dim=16, seed=42):\\n",
    "    '''Generate toy high-dimensional data with cluster structure.'''\\n",
    "    rng = np.random.RandomState(seed)\\n",
    "    X = []\\n",
    "    y = []\\n",
    "    for c in range(n_classes):\\n",
    "        center = rng.randn(dim) * 3\\n",
    "        samples = center + rng.randn(n_samples // n_classes, dim) * 0.5\\n",
    "        X.append(samples)\\n",
    "        y.extend([c] * (n_samples // n_classes))\\n",
    "    return np.vstack(X), np.array(y)\\n",
    "\\n",
    "X_data, y_data = generate_toy_data(n_samples=200, n_classes=4, dim=16, seed=42)\\n",
    "print(f'Toy data: {X_data.shape}, 4 clusters')\\n",
    "\\n",
    "# Simple linear encoder (simulating frozen backbone features)\\n",
    "class SimpleEncoder:\\n",
    "    '''Simple encoder for SimCLR demo.'''\\n",
    "    def __init__(self, input_dim=16, hidden_dim=32, output_dim=16):\\n",
    "        self.W1 = np.random.randn(input_dim, hidden_dim) * 0.1\\n",
    "        self.b1 = np.zeros(hidden_dim)\\n",
    "        self.W2 = np.random.randn(hidden_dim, output_dim) * 0.1\\n",
    "        self.b2 = np.zeros(output_dim)\\n",
    "        # Projection head\\n",
    "        self.Wp = np.random.randn(output_dim, output_dim) * 0.1\\n",
    "        self.bp = np.zeros(output_dim)\\n",
    "    \\n",
    "    def encode(self, x):\\n",
    "        '''Encode input to feature space h.'''\\n",
    "        h = np.maximum(0, x @ self.W1 + self.b1)\\n",
    "        h = h @ self.W2 + self.b2\\n",
    "        return h\\n",
    "    \\n",
    "    def project(self, h):\\n",
    "        '''Project to contrastive space z.'''\\n",
    "        z = np.maximum(0, h @ self.Wp + self.bp)\\n",
    "        return z\\n",
    "\\n",
