    "# Implement InfoNCE loss\\n",
    "def cosine_similarity(a, b):\\n",
    "    '''Compute cosine similarity between rows of a and b.'''\\n",
    "    a_norm = a / (np.linalg.norm(a, axis=1, keepdims=True) + 1e-8)\\n",
    "    b_norm = b / (np.linalg.norm(b, axis=1, keepdims=True) + 1e-8)\\n",
    "    return a_norm @ b_norm.T\\n",
    "\\n",
    "def info_nce_loss(features_q, features_k, temperature=0.1):\\n",
    "    '''Compute InfoNCE loss.\\n",
    "    \\n",
    "    Args:\\n",
    "        features_q: query features (batch_size, feature_dim)\\n",
    "        features_k: key features (batch_size, feature_dim)\\n",
    "        temperature: temperature coefficient\\n",
    "    \\n",
    "    Returns:\\n",
    "        scalar loss value\\n",
    "    '''\\n",
    "    batch_size = len(features_q)\\n",
    "    \\n",
    "    # Compute similarity matrix\\n",
    "    sim_matrix = cosine_similarity(features_q, features_k) / temperature\\n",
    "    \\n",
    "    # Positive pairs are on the diagonal (i,i)\\n",
    "    # Negative pairs are all other positions\\n",
    "    logits = sim_matrix\\n",
    "    \\n",
    "    # Labels: positive sample is at index i for query i\\n",
    "    labels = np.arange(batch_size)\\n",
    "    \\n",
    "    # Numerically stable softmax + cross-entropy\\n",
    "    logits_max = np.max(logits, axis=1, keepdims=True)\\n",
    "    logits_stable = logits - logits_max\\n",
    "    exp_logits = np.exp(logits_stable)\\n",
    "    log_sum_exp = np.log(np.sum(exp_logits, axis=1) + 1e-10)\\n",
    "    \\n",
    "    # Loss = -log(exp(pos) / sum(exp(all))) = log(sum) - pos\\n",
    "    log_probs = logits_stable - log_sum_exp[:, None]\\n",
    "    loss = -np.mean(log_probs[np.arange(batch_size), labels])\\n",
    "    \\n",
    "    return loss\\n",
    "\\n",
