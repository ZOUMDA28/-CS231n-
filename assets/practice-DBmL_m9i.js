    "# SimCLR training loop (simplified)\\n",
    "def train_simclr(X, encoder, epochs=50, lr=0.01, temperature=0.1, batch_size=32):\\n",
    "    '''Simplified SimCLR training loop.'''\\n",
    "    n = len(X)\\n",
    "    losses = []\\n",
    "    rng = np.random.RandomState(42)\\n",
    "    \\n",
    "    for epoch in range(epochs):\\n",
    "        # Shuffle\\n",
    "        indices = rng.permutation(n)\\n",
    "        epoch_loss = 0\\n",
    "        n_batches = 0\\n",
    "        \\n",
    "        for start in range(0, n - batch_size + 1, batch_size):\\n",
    "            batch_idx = indices[start:start + batch_size]\\n",
    "            x_batch = X[batch_idx]\\n",
    "            \\n",
    "            # Two augmentations\\n",
    "            x1 = augment_2d(x_batch, strength=0.3, seed=start + epoch*100)\\n",
    "            x2 = augment_2d(x_batch, strength=0.3, seed=start + epoch*100 + 1)\\n",
    "            \\n",
    "            # Forward pass\\n",
    "            h1 = encoder.encode(x1)\\n",
    "            z1 = encoder.project(h1)\\n",
    "            h2 = encoder.encode(x2)\\n",
    "            z2 = encoder.project(h2)\\n",
    "            \\n",
    "            # Symmetric InfoNCE loss\\n",
    "            loss_12 = info_nce_loss(z1, z2, temperature)\\n",
    "            loss_21 = info_nce_loss(z2, z1, temperature)\\n",
    "            loss = (loss_12 + loss_21) / 2\\n",
    "            epoch_loss += loss\\n",
    "            n_batches += 1\\n",
    "            \\n",
    "            # Simple gradient update (approximate)\\n",
