    "## 3. SimCLR：简单对比学习框架\\n",
    "\\n",
    "### SimCLR 核心思想\\n",
    "\\n",
    "[[Chen et al., 2020]](https://arxiv.org/abs/2002.05709) 提出的 SimCLR 是对比学习的代表作。\\n",
    "\\n",
    "### 架构\\n",
    "\\n",
    "\`\`\`\\n",
    "图像 x\\n",
    "  |\\n",
    "  +-- 增强 t1 --> 编码器 f --> 特征 h --> 投影头 g --> z1\\n",
    "  +-- 增强 t2 --> 编码器 f --> 特征 h --> 投影头 g --> z2\\n",
    "  \\n",
    "损失：InfoNCE(z1, z2) + InfoNCE(z2, z1)\\n",
    "\`\`\`\\n",
    "\\n",
    "### 关键组件\\n",
    "\\n",
    "1. **数据增强**：随机裁剪、颜色抖动、高斯模糊\\n",
    "2. **编码器**：ResNet 等（提取特征 h）\\n",
    "3. **投影头**：小型 MLP（投影到 z 空间计算损失）\\n",
    "4. **损失**：对称 InfoNCE\\n",
    "\\n",
    "### 为什么需要投影头？\\n",
    "\\n",
    "投影头将特征映射到一个更适合计算对比损失的空间。下游任务用 h（编码器输出），不用 z（投影头输出）。\\n",
