    "## 4. 数据增强：对比学习的关键\\n",
    "\\n",
    "### 为什么数据增强这么重要？\\n",
    "\\n",
    "在对比学习中，**正样本对是靠数据增强构造的**。如果增强太弱，模型很容易区分正/负样本，学不到有用特征；如果增强太强，正样本变得不相似，模型会困惑。\\n",
    "\\n",
    "### SimCLR 中的关键增强\\n",
    "\\n",
    "1. **随机裁剪 + 缩放**：不同视角的同一物体\\n",
