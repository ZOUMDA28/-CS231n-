    "## 5. MoCo：动量对比学习\\n",
    "\\n",
    "### 问题：Batch Size 限制\\n",
    "\\n",
    "SimCLR 的效果很大程度依赖于 batch size——负样本越多越好。但 GPU 显存限制了 batch size。\\n",
    "\\n",
    "### MoCo 的解决方案\\n",
    "\\n",
    "[[He et al., 2019]](https://arxiv.org/abs/1911.05722) 提出了 MoCo（Momentum Contrast）：\\n",
    "\\n",
    "1. **队列（Queue）**：保存历史批次的特征作为负样本，不需要全部在一个 batch\\n",
    "2. **动量编码器（Momentum Encoder）**：用 query 编码器的移动平均来更新 key 编码器，保持一致性\\n",
    "\\n",
    "### 动量更新公式\\n",
    "\\n",
    "k_encoder.params = m * k_encoder.params + (1-m) * q_encoder.params\\n",
    "\\n",
    "其中 m 是动量系数（通常 0.999）。\\n",
    "\\n",
    "### 为什么需要动量编码器？\\n",
    "\\n",
    "如果直接用梯度更新 key 编码器，队列中的特征来自不同版本的编码器，不一致。动量编码器提供更平滑稳定的 key 特征。\\n"
