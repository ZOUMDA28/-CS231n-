    "def byol_loss(p_online, z_target):\\n",
    "    '''Compute BYOL loss: MSE between prediction and target.\\n",
    "    \\n",
    "    Args:\\n",
    "        p_online: prediction from online network (batch, dim)\\n",
    "        z_target: projection from target network (batch, dim), no gradient\\n",
    "    \\n",
    "    Returns:\\n",
    "        scalar loss\\n",
    "    '''\\n",
