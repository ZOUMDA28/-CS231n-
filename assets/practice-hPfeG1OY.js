    "### 手动计算：InfoNCE 对比损失\\n",
    "\\n",
    "让我们用一个小例子（batch_size=2）**手动计算** CLIP 的对称对比损失，确保真正理解。\\n",
    "\\n",
    "**设定**：batch 中有 2 对图文对：\\n",
    "- 图像 $I_1$ 对应文本 $T_1$（正样本对）\\n",
    "- 图像 $I_2$ 对应文本 $T_2$（正样本对）\\n",
    "\\n",
    "**Step 1: 余弦相似度矩阵**\\n",
    "\\n",
    "假设 L2 归一化后的余弦相似度为：\\n",
    "\\n",
    "$$S = \\\\begin{bmatrix} \\\\text{sim}(I_1,T_1) & \\\\text{sim}(I_1,T_2) \\\\\\\\ \\\\text{sim}(I_2,T_1) & \\\\text{sim}(I_2,T_2) \\\\end{bmatrix} = \\\\begin{bmatrix} 0.6 & 0.4 \\\\\\\\ 0.3 & 0.7 \\\\end{bmatrix}$$\\n",
    "\\n",
    "对角线 $0.6$ 和 $0.7$ 是正样本对的相似度（较大），非对角线是负样本对（较小）。\\n",
    "\\n",
    "**Step 2: 除以温度参数 $\\\\tau$**\\n",
    "\\n",
    "取 $\\\\tau = 0.1$（CLIP 默认 $0.07$，这里简化为 $0.1$）：\\n",
    "\\n",
    "$$\\\\text{logits} = S / \\\\tau = \\\\begin{bmatrix} 6 & 4 \\\\\\\\ 3 & 7 \\\\end{bmatrix}$$\\n",
    "\\n",
    "**Step 3: Image-to-Text 方向的 softmax**\\n",
    "\\n",
    "对每一行做 softmax（每张图选最匹配的文本）：\\n",
    "\\n",
    "**行 1**（$I_1$ 在 $T_1, T_2$ 之间选择）：\\n",
    "\\n",
    "$$P(T_1|I_1) = \\\\frac{e^6}{e^6 + e^4} = \\\\frac{403.4}{403.4 + 54.6} = \\\\frac{403.4}{458.0} \\\\approx 0.881$$\\n",
    "\\n",
    "$$P(T_2|I_1) = \\\\frac{e^4}{e^6 + e^4} = \\\\frac{54.6}{458.0} \\\\approx 0.119$$\\n",
    "\\n",
    "**行 2**（$I_2$ 在 $T_1, T_2$ 之间选择）：\\n",
    "\\n",
    "$$P(T_1|I_2) = \\\\frac{e^3}{e^3 + e^7} = \\\\frac{20.1}{20.1 + 1096.6} = \\\\frac{20.1}{1116.7} \\\\approx 0.018$$\\n",
    "\\n",
    "$$P(T_2|I_2) = \\\\frac{e^7}{e^3 + e^7} = \\\\frac{1096.6}{1116.7} \\\\approx 0.982$$\\n",
    "\\n",
    "**Step 4: 计算交叉熵损失（Image-to-Text）**\\n",
    "\\n",
    "正确标签是对角线：$I_1 \\\\to T_1$, $I_2 \\\\to T_2$\\n",
    "\\n",
    "$$\\\\mathcal{L}_{i2t} = -\\\\frac{1}{2}\\\\left[\\\\log P(T_1|I_1) + \\\\log P(T_2|I_2)\\\\right]$$\\n",
    "\\n",
    "$$= -\\\\frac{1}{2}\\\\left[\\\\log 0.881 + \\\\log 0.982\\\\right]$$\\n",
    "\\n",
    "$$= -\\\\frac{1}{2}\\\\left[(-0.127) + (-0.018)\\\\right] = -\\\\frac{1}{2}(-0.145) = 0.073$$\\n",
    "\\n",
    "**Step 5: Text-to-Image 方向**\\n",
    "\\n",
    "对列做 softmax（每个文本选最匹配的图像）：\\n",
    "\\n",
    "**列 1**（$T_1$ 在 $I_1, I_2$ 之间选择）：\\n",
    "\\n",
    "$$P(I_1|T_1) = \\\\frac{e^6}{e^6 + e^3} = \\\\frac{403.4}{423.5} \\\\approx 0.953, \\\\quad P(I_2|T_1) \\\\approx 0.047$$\\n",
    "\\n",
    "**列 2**（$T_2$ 在 $I_1, I_2$ 之间选择）：\\n",
    "\\n",
    "$$P(I_1|T_2) = \\\\frac{e^4}{e^4 + e^7} = \\\\frac{54.6}{1151.2} \\\\approx 0.047, \\\\quad P(I_2|T_2) \\\\approx 0.953$$\\n",
    "\\n",
    "$$\\\\mathcal{L}_{t2i} = -\\\\frac{1}{2}\\\\left[\\\\log 0.953 + \\\\log 0.953\\\\right] = -\\\\frac{1}{2}\\\\left[(-0.048) + (-0.048)\\\\right] = 0.048$$\\n",
    "\\n",
    "**Step 6: 总损失**\\n",
    "\\n",
    "$$\\\\mathcal{L}_{\\\\text{CLIP}} = \\\\frac{\\\\mathcal{L}_{i2t} + \\\\mathcal{L}_{t2i}}{2} = \\\\frac{0.073 + 0.048}{2} = 0.061$$\\n",
    "\\n",
    "> **关键观察**：\\n",
    "> - 当正样本相似度远大于负样本时（$0.6/0.7$ vs $0.4/0.3$），损失很小，模型已学到正确配对\\n",
