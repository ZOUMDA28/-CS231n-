    "## 2. CLIP：对比语言-图像预训练\\n",
    "\\n",
    "### 核心思想\\n",
    "\\n",
    "[[Radford et al., 2021]](https://arxiv.org/abs/2103.00020)\\n",
    "\\n",
    "**用 4 亿对图像-文本数据做对比学习**\\n",
    "\\n",
    "### 架构\\n",
    "\\n",
    "\`\`\`\\n",
    "图像 --> 图像编码器 --> 图像嵌入 (I)\\n",
    "文本 --> 文本编码器 --> 文本嵌入 (T)\\n",
    "\\n",
    "损失：对称对比损失 (InfoNCE)\\n",
    "- 每个图像找到对应的文本（正样本）\\n",
    "- 每个文本找到对应的图像（正样本）\\n",
    "\`\`\`\\n",
    "\\n",
    "### 训练目标\\n",
    "\\n",
    "在一个 batch 中：\\n",
    "- 行方向：每个图像和 batch 内所有文本计算相似度，正确的文本应该最相似\\n",
    "- 列方向：每个文本和 batch 内所有图像计算相似度，正确的图像应该最相似\\n",
    "\\n",
    "### 为什么 CLIP 这么强？\\n",
    "\\n",
    "1. **海量数据**：4 亿图文对，远超 ImageNet\\n",
    "2. **弱监督**：不需要精确标注，图片+描述就行\\n",
    "3. **对比学习**：学到语义级别的相似性\\n",
    "4. **双编码器**：图像和文本共享嵌入空间\\n"
