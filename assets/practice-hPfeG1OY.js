    "# Implement CLIP-style contrastive loss\\n",
    "def clip_contrastive_loss(image_emb, text_emb, temperature=0.07):\\n",
    "    '''CLIP-style symmetric contrastive loss.\\n",
    "    \\n",
    "    Args:\\n",
    "        image_emb: image embeddings (batch, dim)\\n",
    "        text_emb: text embeddings (batch, dim)\\n",
    "        temperature: temperature parameter\\n",
    "    \\n",
    "    Returns:\\n",
    "        total loss (image-to-text + text-to-image) / 2\\n",
    "    '''\\n",
    "    # Normalize embeddings\\n",
    "    img_norm = image_emb / (np.linalg.norm(image_emb, axis=1, keepdims=True) + 1e-8)\\n",
    "    txt_norm = text_emb / (np.linalg.norm(text_emb, axis=1, keepdims=True) + 1e-8)\\n",
    "    \\n",
    "    # Similarity matrix (batch x batch)\\n",
    "    logits = img_norm @ txt_norm.T / temperature\\n",
    "    \\n",
    "    batch_size = len(image_emb)\\n",
    "    labels = np.arange(batch_size)\\n",
    "    \\n",
    "    # Image-to-text loss\\n",
    "    logits_i2t_max = np.max(logits, axis=1, keepdims=True)\\n",
    "    logits_i2t_stable = logits - logits_i2t_max\\n",
    "    exp_i2t = np.exp(logits_i2t_stable)\\n",
    "    log_sum_i2t = np.log(np.sum(exp_i2t, axis=1) + 1e-10)\\n",
    "    log_probs_i2t = logits_i2t_stable - log_sum_i2t[:, None]\\n",
    "    loss_i2t = -np.mean(log_probs_i2t[labels, labels])\\n",
    "    \\n",
    "    # Text-to-image loss\\n",
    "    logits_t2i = logits.T\\n",
    "    logits_t2i_max = np.max(logits_t2i, axis=1, keepdims=True)\\n",
    "    logits_t2i_stable = logits_t2i - logits_t2i_max\\n",
    "    exp_t2i = np.exp(logits_t2i_stable)\\n",
    "    log_sum_t2i = np.log(np.sum(exp_t2i, axis=1) + 1e-10)\\n",
    "    log_probs_t2i = logits_t2i_stable - log_sum_t2i[:, None]\\n",
    "    loss_t2i = -np.mean(log_probs_t2i[labels, labels])\\n",
    "    \\n",
    "    return (loss_i2t + loss_t2i) / 2\\n",
    "\\n",
    "# Test with toy embeddings\\n",
    "np.random.seed(42)\\n",
    "batch_size = 8\\n",
    "dim = 32\\n",
    "\\n",
    "# Simulate paired embeddings (slightly different but correlated)\\n",
    "img_emb = np.random.randn(batch_size, dim)\\n",
    "text_emb = img_emb + np.random.randn(batch_size, dim) * 0.3  # text similar to image\\n",
    "\\n",
    "loss = clip_contrastive_loss(img_emb, text_emb, temperature=0.07)\\n",
    "print(f'CLIP contrastive loss: {loss:.4f}')\\n",
    "\\n",
    "# Test with random (unpaired) embeddings\\n",
    "random_text = np.random.randn(batch_size, dim)\\n",
